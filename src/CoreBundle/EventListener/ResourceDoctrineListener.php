declare(strict_types=1);

namespace Chamilo\CoreBundle\EventListener;

use Chamilo\CoreBundle\Entity\AbstractResource;
use Chamilo\CoreBundle\Entity\ResourceLink;
use Chamilo\CoreBundle\Entity\ResourceNode;
use Chamilo\CoreBundle\Helpers\ResourceHelper;
use Doctrine\Bundle\DoctrineBundle\Attribute\AsDoctrineListener;
use Doctrine\ORM\EntityManagerInterface;
use Doctrine\ORM\Event\OnFlushEventArgs;
use Doctrine\ORM\Event\PostPersistEventArgs;
use Doctrine\ORM\Event\PostUpdateEventArgs;
use Doctrine\ORM\Events;

/**
 * Writes the track_e_default audit rows for resource lifecycle events.
 *
 * Every row is written with a direct DBAL insert from inside the flush that
 * caused it, so it shares that flush's transaction and is rolled back with it.
 * Calling EntityManager::flush() from a listener dispatched by flush() itself
 * is explicitly unsafe (see Doctrine's events documentation), which rules out
 * persisting these rows through the ORM.
 */
#[AsDoctrineListener(event: Events::onFlush, connection: 'default')]
#[AsDoctrineListener(event: Events::postPersist, connection: 'default')]
#[AsDoctrineListener(event: Events::postUpdate, connection: 'default')]
class ResourceDoctrineListener
{
    public function __construct(
        private readonly EntityManagerInterface $entityManager,
        private readonly ResourceHelper $trackEDefaultHelper,
    ) {}

    /**
     * Handles the events whose data is only intact before the flush runs:
     * a removed resource still has its resource links loadable here, and a
     * resource link scheduled for update still exposes its changeset.
     */
    public function onFlush(OnFlushEventArgs $args): void
    {
        $unitOfWork = $args->getObjectManager()->getUnitOfWork();

        foreach ($unitOfWork->getScheduledEntityDeletions() as $entity) {
            if (!$entity instanceof AbstractResource) {
                continue;
            }

            $this->track($entity->getResourceNode(), 'deletion');
        }

        foreach ($unitOfWork->getScheduledEntityUpdates() as $entity) {
            if (!$entity instanceof ResourceLink) {
                continue;
            }

            $changeSet = $unitOfWork->getEntityChangeSet($entity);

            if (!isset($changeSet['visibility'])) {
                continue;
            }

            $this->track($entity->getResourceNode(), 'visibility_change');
        }
    }

    /**
     * Creation is tracked here and not in onFlush because the resource node id
     * is generated by the insert itself and is still null while onFlush runs.
     */
    public function postPersist(PostPersistEventArgs $args): void
    {
        $resource = $args->getObject();

        if (!$resource instanceof AbstractResource) {
            return;
        }

        $this->track($resource->getResourceNode(), 'creation');
    }

    public function postUpdate(PostUpdateEventArgs $args): void
    {
        $resource = $args->getObject();

        if (!$resource instanceof AbstractResource) {
            return;
        }

        $this->track($resource->getResourceNode(), 'edition');
    }

    private function track(?ResourceNode $resourceNode, string $eventType): void
    {
        if (null === $resourceNode) {
            return;
        }

        $event = $this->trackEDefaultHelper->createResourceEvent($resourceNode, $eventType);

        if (null === $event) {
            return;
        }

        $this->entityManager->getConnection()->insert('track_e_default', [
            'default_user_id' => $event->getDefaultUserId(),
            'c_id' => $event->getCId(),
            'default_date' => $event->getDefaultDate()->format('Y-m-d H:i:s'),
            'default_event_type' => $event->getDefaultEventType(),
            'default_value_type' => $event->getDefaultValueType(),
            'default_value' => $event->getDefaultValue(),
            'session_id' => $event->getSessionId(),
        ]);
    }
}
