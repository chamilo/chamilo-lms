declare(strict_types=1);

namespace Chamilo\CoreBundle\Service\Exercise;

use Chamilo\CoreBundle\AiProvider\AiProviderFactory;
use Chamilo\CoreBundle\Entity\Course;
use Chamilo\CoreBundle\Helpers\AiFeatureAccessHelper;
use InvalidArgumentException;
use RuntimeException;
use TypeError;

final readonly class ExerciseRegressionTopicContentGenerator
{
    public function __construct(
        private AiProviderFactory $aiProviderFactory,
        private AiFeatureAccessHelper $aiFeatureAccessHelper,
        private ExerciseRegressionTopicContentParser $parser,
    ) {}

    /**
     * @return array{content: array<string, mixed>, provider: string}
     */
    public function generate(
        Course $course,
        string $topic,
        string $language = 'en',
        ?string $providerName = null,
    ): array {
        $courseId = (int) ($course->getId() ?? 0);
        if ($courseId <= 0) {
            throw new InvalidArgumentException('A persisted course is required for topic-aware regression content.');
        }

        if (!$this->aiFeatureAccessHelper->isFeatureEnabledForCourse('exercise_generator', $courseId)) {
            throw new RuntimeException('AI exercise generation is not enabled for this course.');
        }

        $providers = $this->aiProviderFactory->getProvidersForType('text');
        if ([] === $providers) {
            throw new RuntimeException('No AI text provider is configured for topic-aware exercise generation.');
        }

        $providerName = trim((string) ($providerName ?? ''));
        if ('' === $providerName) {
            $providerName = (string) $providers[0];
        }
        if (!\in_array($providerName, $providers, true)) {
            throw new InvalidArgumentException('The requested AI text provider is not available: '.$providerName);
        }

        $provider = $this->aiProviderFactory->getProvider($providerName, 'text');
        if (!method_exists($provider, 'generateText')) {
            throw new RuntimeException('The selected AI provider does not support structured text generation.');
        }

        $prompt = $this->buildPrompt($course, $topic, $language);

        try {
            $raw = (string) $provider->generateText($prompt, [
                'language' => $language,
                'tool' => 'mcp_exercise_regression_topic_suite',
                'cid' => $courseId,
                'temperature' => 0.2,
                'max_tokens' => 6000,
            ]);
        } catch (TypeError) {
            $raw = (string) $provider->generateText($prompt, $language);
        }

        $raw = trim($raw);
        if ('' === $raw || str_starts_with(strtolower($raw), 'error:')) {
            throw new RuntimeException('The AI provider could not generate topic-aware exercise content.');
        }

        return [
            'content' => $this->parser->parse($raw),
            'provider' => $providerName,
        ];
    }

    private function buildPrompt(Course $course, string $topic, string $language): string
    {
        $courseTitle = trim(strip_tags((string) $course->getTitle()));

        return <<<PROMPT
You are an expert teacher preparing realistic regression-test content for Chamilo Exercises.

Course: {$courseTitle}
Topic: {$topic}
Language: {$language}

Create coherent, factually consistent assessment content about the topic. The content will be reused across Chamilo's different question widgets, so every item must make pedagogical sense and must not mention software testing, QA, Chamilo question type numbers, placeholders, or that it was generated by AI.

Return ONLY one valid JSON object. Do not use markdown fences and do not add commentary before or after the JSON.

Required JSON shape:
{
  "single_choice": {
    "question": "...",
    "options": ["...", "...", "..."],
    "correct_index": 0,
    "feedback": "..."
  },
  "multiple_choice": {
    "question": "...",
    "options": ["...", "...", "...", "..."],
    "correct_indexes": [0, 1],
    "feedback": "..."
  },
  "fill_blanks": {
    "question": "...",
    "template": "A meaningful sentence using {blank1} and later {blank2}.",
    "answers": ["...", "..."],
    "feedback": "..."
  },
  "matching": {
    "question": "...",
    "pairs": [
      {"left": "...", "right": "..."},
      {"left": "...", "right": "..."}
    ],
    "feedback": "..."
  },
  "open": {"question": "..."},
  "true_false": {
    "question": "...",
    "true_statement": "A factually true statement.",
    "false_statement": "A clearly false statement.",
    "feedback": "..."
  },
  "oral": {"question": "..."},
  "media": {"title": "...", "context": "A short explanatory context paragraph."},
  "calculated": {
    "question": "...",
    "context": "A topic-related scenario where adding two generated quantities is meaningful:",
    "unit": "optional unit",
    "feedback": "..."
  },
  "image_choice": {
    "question": "...",
    "correct_label": "...",
    "wrong_label": "...",
    "feedback": "..."
  },
  "ordering": {
    "question": "...",
    "items": ["First chronological/logical step", "Second chronological/logical step"],
    "feedback": "..."
  },
  "annotation": {"question": "..."},
  "reading": {"title": "...", "passage": "A self-contained passage of 3 to 5 sentences about the topic."},
  "upload": {"question": "..."},
  "dropdown": {
    "question": "...",
    "options": ["...", "...", "..."],
    "correct_index": 0,
    "feedback": "..."
  },
  "hotspot": {"question": "...", "target_label": "..."},
  "office": {"question": "..."},
  "page_break": {"title": "...", "text": "..."}
}

Rules:
- Use zero-based indexes for correct_index and correct_indexes.
- single_choice must have exactly 3 distinct options and exactly one correct option.
- multiple_choice must have exactly 4 distinct options and at least 2 correct options.
- dropdown must have exactly 3 distinct options and exactly one correct option.
- fill_blanks must use both literal tokens {blank1} and {blank2}; answers must contain only the missing words/short phrases.
- matching must contain exactly 2 unambiguous pairs.
- ordering must contain exactly 2 items in the correct order.
- true_statement must be true and false_statement must be false.
- calculated.context must describe quantities that can be added; do not include formulas or numbers because Chamilo supplies [x] and [y].
- image_choice labels should be meaningful captions; the regression suite supplies the test images itself.
- hotspot and annotation use technical regression images, so make the instruction generic enough to remain valid without claiming the image depicts a real-world object.
- upload and office prompts should request a short learner-produced artifact about the topic.
- Keep questions concise and suitable for a general learner unless the topic itself implies a specialized level.
PROMPT;
    }
}
